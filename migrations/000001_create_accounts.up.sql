-- Accounts, sessions, and single sign-on links. Credentials live at the
-- provider: this app stores no passwords, only the issuer subject per account.
CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255),
    username VARCHAR(32),
    display_name VARCHAR(255),
    is_guest BOOLEAN NOT NULL DEFAULT FALSE,
    is_admin BOOLEAN NOT NULL DEFAULT FALSE,
    theme VARCHAR(20) NOT NULL DEFAULT 'light',
    locale VARCHAR(10) NOT NULL DEFAULT 'en',
    created_at BIGINT NOT NULL,
    email_verified_at BIGINT,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT users_guest_credentials CHECK (
        NOT is_guest OR (email IS NULL AND email_verified_at IS NULL)
    ),
    CONSTRAINT users_email_normalized CHECK (
        email IS NULL OR email = lower(btrim(email))
    ),
    CONSTRAINT users_username_normalized CHECK (
        username IS NULL OR username = lower(btrim(username))
    ),
    CONSTRAINT users_username_nonempty CHECK (
        username IS NULL OR length(username) > 0
    ),
    CONSTRAINT users_username_no_at CHECK (
        username IS NULL OR position('@' IN username) = 0
    ),
    CONSTRAINT users_theme_allowed CHECK (theme IN ('light', 'dark')),
    CONSTRAINT users_version_nonnegative CHECK (version >= 0)
);

CREATE UNIQUE INDEX users_email_unique_idx ON users (email) WHERE email IS NOT NULL;
CREATE UNIQUE INDEX users_username_unique_idx ON users (username) WHERE username IS NOT NULL;

-- Session IDs are stored as SHA-256 hex digests. sso_sid binds a session to
-- the Hydra login session that created it so a back-channel logout revokes
-- exactly those sessions; sso_id_token is the id_token_hint Hydra requires for
-- sign-out with a return URL. Neither is a credential for this app, and both
-- are never rendered or logged.
CREATE TABLE sessions (
    id VARCHAR(64) PRIMARY KEY,
    user_id BIGINT NOT NULL,
    created_at BIGINT NOT NULL,
    expires_at BIGINT NOT NULL,
    revoked_at BIGINT,
    sso_sid VARCHAR(128),
    sso_id_token TEXT,
    CONSTRAINT sessions_expiry_after_creation CHECK (expires_at > created_at),
    CONSTRAINT sessions_sso_sid_nonempty CHECK (sso_sid IS NULL OR length(sso_sid) > 0),
    CONSTRAINT sessions_sso_id_token_size CHECK (sso_id_token IS NULL OR length(sso_id_token) BETWEEN 1 AND 16384),
    CONSTRAINT sessions_user_id_fk FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

CREATE INDEX sessions_user_id_idx ON sessions (user_id);
CREATE INDEX sessions_sso_sid_idx ON sessions (sso_sid) WHERE sso_sid IS NOT NULL;

CREATE TABLE oauth_identities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    provider VARCHAR(32) NOT NULL,
    subject VARCHAR(255) NOT NULL,
    email VARCHAR(255),
    created_at BIGINT NOT NULL,
    CONSTRAINT oauth_identities_provider_subject_unique UNIQUE (provider, subject),
    CONSTRAINT oauth_identities_user_id_fk FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

CREATE INDEX oauth_identities_user_id_idx ON oauth_identities (user_id);

-- One-time sign-in flow state, stored as a SHA-256 hex digest. code_verifier
-- is the PKCE (RFC 7636) secret that redeems the flow's authorization code.
CREATE TABLE oauth_states (
    state VARCHAR(64) PRIMARY KEY,
    provider VARCHAR(32) NOT NULL,
    action VARCHAR(16) NOT NULL,
    user_id BIGINT,
    code_verifier VARCHAR(128),
    created_at BIGINT NOT NULL,
    expires_at BIGINT NOT NULL,
    consumed_at BIGINT,
    CONSTRAINT oauth_states_action_allowed CHECK (action IN ('sign-in', 'link')),
    CONSTRAINT oauth_states_expiry_after_creation CHECK (expires_at > created_at),
    CONSTRAINT oauth_states_user_id_fk FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

CREATE INDEX oauth_states_user_id_idx ON oauth_states (user_id);
CREATE INDEX oauth_states_expires_at_idx ON oauth_states (expires_at);

CREATE TABLE guest_claim_codes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    code VARCHAR(64) NOT NULL UNIQUE,
    created_at BIGINT NOT NULL,
    last_used_at BIGINT,
    revoked_at BIGINT,
    CONSTRAINT guest_claim_codes_user_id_fk FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

CREATE INDEX guest_claim_codes_user_id_idx ON guest_claim_codes (user_id);
CREATE UNIQUE INDEX guest_claim_codes_active_user_idx
    ON guest_claim_codes (user_id)
    WHERE revoked_at IS NULL;
