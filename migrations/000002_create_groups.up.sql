-- Groups are clubs. Every group-scoped table carries group_id (directly or
-- through its parent) so each query is scoped to one group.
CREATE TABLE groups (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(64) NOT NULL,
    name_norm VARCHAR(64) NOT NULL,
    invite_code VARCHAR(64) NOT NULL UNIQUE,
    -- IANA time zone name; the application validates it with the embedded
    -- time zone database before writing.
    time_zone VARCHAR(64) NOT NULL DEFAULT 'Europe/Budapest',
    created_by BIGINT,
    created_at BIGINT NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT groups_name_nonempty CHECK (length(btrim(name)) > 0),
    CONSTRAINT groups_name_norm_normalized CHECK (name_norm = lower(btrim(name_norm))),
    CONSTRAINT groups_name_norm_nonempty CHECK (length(name_norm) > 0),
    CONSTRAINT groups_invite_code_nonempty CHECK (length(invite_code) > 0),
    CONSTRAINT groups_time_zone_nonempty CHECK (length(time_zone) > 0),
    CONSTRAINT groups_version_nonnegative CHECK (version >= 0),
    CONSTRAINT groups_created_by_fk FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE SET NULL
);

CREATE INDEX groups_name_norm_idx ON groups (name_norm);

-- One row per member. version is bumped by every role change so roster
-- forms are revision checked.
CREATE TABLE group_members (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    created_at BIGINT NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT group_members_group_user_unique UNIQUE (group_id, user_id),
    CONSTRAINT group_members_version_nonnegative CHECK (version >= 0),
    CONSTRAINT group_members_group_id_fk FOREIGN KEY (group_id) REFERENCES groups (id) ON DELETE CASCADE,
    CONSTRAINT group_members_user_id_fk FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

CREATE INDEX group_members_user_id_idx ON group_members (user_id);

-- Several roles per member; permissions are the union. Admin, manager, and
-- coach need a full account (users.kind = 'account'); the application checks
-- that inside the writing transaction.
CREATE TABLE group_member_roles (
    group_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    role VARCHAR(16) NOT NULL,
    created_at BIGINT NOT NULL,
    PRIMARY KEY (group_id, user_id, role),
    CONSTRAINT group_member_roles_role_allowed CHECK (role IN ('admin', 'manager', 'coach', 'player', 'parent')),
    CONSTRAINT group_member_roles_member_fk FOREIGN KEY (group_id, user_id)
        REFERENCES group_members (group_id, user_id) ON DELETE CASCADE
);

CREATE INDEX group_member_roles_role_idx ON group_member_roles (group_id, role);

-- A team is a birth-year range plus a name and persists across seasons.
CREATE TABLE teams (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id BIGINT NOT NULL,
    name VARCHAR(64) NOT NULL,
    birth_year_from SMALLINT NOT NULL,
    birth_year_to SMALLINT NOT NULL,
    description VARCHAR(255),
    archived_at BIGINT,
    created_at BIGINT NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT teams_group_id_unique UNIQUE (group_id, id),
    CONSTRAINT teams_name_nonempty CHECK (length(btrim(name)) > 0),
    CONSTRAINT teams_birth_years_valid CHECK (
        birth_year_from BETWEEN 1900 AND 2200
        AND birth_year_to BETWEEN 1900 AND 2200
        AND birth_year_from <= birth_year_to
    ),
    CONSTRAINT teams_description_nonempty CHECK (description IS NULL OR length(btrim(description)) > 0),
    CONSTRAINT teams_version_nonnegative CHECK (version >= 0),
    CONSTRAINT teams_group_id_fk FOREIGN KEY (group_id) REFERENCES groups (id) ON DELETE CASCADE
);

CREATE INDEX teams_group_id_idx ON teams (group_id, archived_at);

-- Players and parents belong to teams until someone changes it by hand. The
-- roster role must be one of the member's group roles: removing that role,
-- or the member, removes the roster entry with it.
CREATE TABLE team_members (
    group_id BIGINT NOT NULL,
    team_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    role VARCHAR(16) NOT NULL,
    created_at BIGINT NOT NULL,
    PRIMARY KEY (team_id, user_id, role),
    CONSTRAINT team_members_role_allowed CHECK (role IN ('player', 'parent')),
    CONSTRAINT team_members_team_fk FOREIGN KEY (group_id, team_id)
        REFERENCES teams (group_id, id) ON DELETE CASCADE,
    CONSTRAINT team_members_role_fk FOREIGN KEY (group_id, user_id, role)
        REFERENCES group_member_roles (group_id, user_id, role) ON DELETE CASCADE
);

CREATE INDEX team_members_member_idx ON team_members (group_id, user_id);
