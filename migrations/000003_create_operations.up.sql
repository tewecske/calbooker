-- Administrator audit trail, request usage, and shared rate-limit counters.
-- History survives account deletion with a nullable reference.
CREATE TABLE audit_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    occurred_at BIGINT NOT NULL,
    actor_user_id BIGINT,
    actor_email VARCHAR(255),
    action VARCHAR(64) NOT NULL,
    target_type VARCHAR(32),
    target_id VARCHAR(64),
    detail VARCHAR(1000),
    ip VARCHAR(64),
    CONSTRAINT audit_log_actor_user_id_fk FOREIGN KEY (actor_user_id) REFERENCES users (id) ON DELETE SET NULL
);

CREATE INDEX audit_log_occurred_at_idx ON audit_log (occurred_at);
CREATE INDEX audit_log_actor_user_id_idx ON audit_log (actor_user_id);
CREATE INDEX audit_log_target_idx ON audit_log (target_type, target_id);

CREATE TABLE usage_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at BIGINT NOT NULL,
    method VARCHAR(8) NOT NULL,
    route VARCHAR(255) NOT NULL,
    status INTEGER NOT NULL,
    user_id BIGINT,
    ip VARCHAR(64),
    request_id VARCHAR(64),
    trace_id VARCHAR(32),
    CONSTRAINT usage_events_method_nonempty CHECK (length(method) > 0),
    CONSTRAINT usage_events_route_nonempty CHECK (length(route) > 0),
    CONSTRAINT usage_events_route_without_query CHECK (position('?' IN route) = 0),
    CONSTRAINT usage_events_status_valid CHECK (status BETWEEN 100 AND 599),
    CONSTRAINT usage_events_user_id_fk FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE SET NULL
);

CREATE INDEX usage_events_created_at_idx ON usage_events (created_at);
CREATE INDEX usage_events_route_created_at_idx ON usage_events (route, created_at);
CREATE INDEX usage_events_user_id_created_at_idx ON usage_events (user_id, created_at);
CREATE INDEX usage_events_request_id_idx ON usage_events (request_id);
CREATE INDEX usage_events_trace_id_idx ON usage_events (trace_id);

-- Fixed-window attempt counters for the rate-limited actions, shared by every
-- instance of the app so a restart or a second instance does not reset or
-- multiply the budgets. Keys (client addresses) are stored only as a SHA-256
-- hash plus a redacted hint for the administrator view. Times are Unix
-- milliseconds.
CREATE TABLE rate_limit_buckets (
    scope VARCHAR(64) NOT NULL,
    action VARCHAR(255) NOT NULL,
    key_hash BYTEA NOT NULL,
    key_hint VARCHAR(255) NOT NULL,
    hit_count INTEGER NOT NULL,
    started_at BIGINT NOT NULL,
    expires_at BIGINT NOT NULL,
    PRIMARY KEY (scope, action, key_hash),
    CONSTRAINT rate_limit_buckets_scope_nonempty CHECK (length(scope) > 0),
    CONSTRAINT rate_limit_buckets_action_nonempty CHECK (length(action) > 0),
    CONSTRAINT rate_limit_buckets_count_positive CHECK (hit_count > 0),
    CONSTRAINT rate_limit_buckets_expiry_after_start CHECK (expires_at > started_at)
);

CREATE INDEX rate_limit_buckets_expires_at_idx ON rate_limit_buckets (expires_at);
