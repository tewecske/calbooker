-- Role-specific invite codes replace the single group invite code (#3).
-- Codes are bearer secrets: they are stored so staff can share them again,
-- but audit entries and logs name an invite only by its id.
CREATE TABLE group_invites (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id BIGINT NOT NULL,
    code VARCHAR(64) NOT NULL,
    role VARCHAR(16) NOT NULL,
    team_id BIGINT,
    expires_at BIGINT,
    max_uses INTEGER,
    uses INTEGER NOT NULL DEFAULT 0,
    created_by BIGINT,
    created_at BIGINT NOT NULL,
    revoked_at BIGINT,
    CONSTRAINT group_invites_code_unique UNIQUE (code),
    CONSTRAINT group_invites_code_nonempty CHECK (length(code) > 0),
    CONSTRAINT group_invites_role_allowed CHECK (role IN ('admin', 'manager', 'coach', 'player', 'parent')),
    -- A team invite puts the new member on the team's roster, which holds
    -- only players and parents.
    CONSTRAINT group_invites_team_role CHECK (team_id IS NULL OR role IN ('player', 'parent')),
    CONSTRAINT group_invites_max_uses_positive CHECK (max_uses IS NULL OR max_uses > 0),
    CONSTRAINT group_invites_uses_valid CHECK (uses >= 0 AND (max_uses IS NULL OR uses <= max_uses)),
    CONSTRAINT group_invites_expiry_after_creation CHECK (expires_at IS NULL OR expires_at > created_at),
    CONSTRAINT group_invites_group_id_fk FOREIGN KEY (group_id) REFERENCES groups (id) ON DELETE CASCADE,
    CONSTRAINT group_invites_team_fk FOREIGN KEY (group_id, team_id)
        REFERENCES teams (group_id, id) ON DELETE CASCADE,
    CONSTRAINT group_invites_created_by_fk FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE SET NULL
);

CREATE INDEX group_invites_group_id_idx ON group_invites (group_id, revoked_at);

