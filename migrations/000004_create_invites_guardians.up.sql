-- A child profile is a users row with kind = 'profile' (it never signs in and
-- guest retention never removes it). This table holds what only profiles
-- have: the group that owns the profile and the birth year. Deleting the
-- profile deletes its users row, which cascades here.
CREATE TABLE child_profiles (
    user_id BIGINT PRIMARY KEY,
    group_id BIGINT NOT NULL,
    birth_year SMALLINT NOT NULL,
    created_by BIGINT,
    created_at BIGINT NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT child_profiles_birth_year_valid CHECK (birth_year BETWEEN 1900 AND 2200),
    CONSTRAINT child_profiles_version_nonnegative CHECK (version >= 0),
    CONSTRAINT child_profiles_user_id_fk FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT child_profiles_group_id_fk FOREIGN KEY (group_id) REFERENCES groups (id) ON DELETE CASCADE,
    CONSTRAINT child_profiles_created_by_fk FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE SET NULL
);

CREATE INDEX child_profiles_group_id_idx ON child_profiles (group_id);

-- A guardian links a parent to a child (a profile or a member account) in
-- one group. The parent must hold the parent role: removing the role, or
-- either member, removes the link. Linked parents appear on the child's
-- teams' rosters as parents; that is derived from this table, not stored in
-- team_members.
CREATE TABLE guardians (
    group_id BIGINT NOT NULL,
    parent_user_id BIGINT NOT NULL,
    parent_role VARCHAR(16) NOT NULL DEFAULT 'parent',
    child_user_id BIGINT NOT NULL,
    created_by BIGINT,
    created_at BIGINT NOT NULL,
    PRIMARY KEY (group_id, parent_user_id, child_user_id),
    CONSTRAINT guardians_parent_role_fixed CHECK (parent_role = 'parent'),
    CONSTRAINT guardians_not_self CHECK (parent_user_id <> child_user_id),
    CONSTRAINT guardians_parent_fk FOREIGN KEY (group_id, parent_user_id, parent_role)
        REFERENCES group_member_roles (group_id, user_id, role) ON DELETE CASCADE,
    CONSTRAINT guardians_child_fk FOREIGN KEY (group_id, child_user_id)
        REFERENCES group_members (group_id, user_id) ON DELETE CASCADE,
    CONSTRAINT guardians_created_by_fk FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE SET NULL
);

CREATE INDEX guardians_child_idx ON guardians (group_id, child_user_id);
