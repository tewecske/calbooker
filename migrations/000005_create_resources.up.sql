-- Resources a club books: fields, courts, halls, pools, rooms (#4).
-- Archived resources stay so plans and events that reference them keep
-- their resource; they are not offered for new plans and events.
CREATE TABLE resources (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id BIGINT NOT NULL,
    name VARCHAR(64) NOT NULL,
    kind VARCHAR(16) NOT NULL,
    description VARCHAR(255),
    -- How many teams may use the resource at the same time; NULL is no limit.
    max_concurrent_teams SMALLINT,
    archived_at BIGINT,
    created_at BIGINT NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    -- Plan slots (#5, #13) and events (#8) reference (group_id, id), so a
    -- reference can never cross groups.
    CONSTRAINT resources_group_id_unique UNIQUE (group_id, id),
    CONSTRAINT resources_name_nonempty CHECK (length(btrim(name)) > 0),
    CONSTRAINT resources_kind_allowed CHECK (kind IN ('field', 'court', 'hall', 'pool', 'room', 'other')),
    CONSTRAINT resources_description_nonempty CHECK (description IS NULL OR length(btrim(description)) > 0),
    CONSTRAINT resources_max_concurrent_teams_valid CHECK (max_concurrent_teams IS NULL OR max_concurrent_teams BETWEEN 1 AND 99),
    CONSTRAINT resources_version_nonnegative CHECK (version >= 0),
    CONSTRAINT resources_group_id_fk FOREIGN KEY (group_id) REFERENCES groups (id) ON DELETE CASCADE
);

-- Names are unique per group among resources in use; an archived resource
-- frees its name.
CREATE UNIQUE INDEX resources_active_name_unique ON resources (group_id, lower(name)) WHERE archived_at IS NULL;

CREATE INDEX resources_group_id_idx ON resources (group_id, archived_at);
