-- Seasons with one or two parts, and per-season coach assignments (#5).
-- Dates are calendar days in the group's time zone (inclusive on both
-- ends). Later tables reference a season as (group_id, season_id) and a
-- season part as (group_id, season_part_id), so a reference never crosses
-- groups.
CREATE TABLE seasons (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id BIGINT NOT NULL,
    name VARCHAR(64) NOT NULL,
    starts_on DATE NOT NULL,
    ends_on DATE NOT NULL,
    created_at BIGINT NOT NULL,
    -- Covers the season and its parts: they are edited together.
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT seasons_group_id_unique UNIQUE (group_id, id),
    CONSTRAINT seasons_name_nonempty CHECK (length(btrim(name)) > 0),
    CONSTRAINT seasons_dates_ordered CHECK (starts_on < ends_on),
    CONSTRAINT seasons_version_nonnegative CHECK (version >= 0),
    CONSTRAINT seasons_group_id_fk FOREIGN KEY (group_id) REFERENCES groups (id) ON DELETE CASCADE,
    -- Seasons of a group never overlap, so the season containing a day (the
    -- current season) is unique. Range types have built-in GiST support, so
    -- this needs no extension.
    CONSTRAINT seasons_no_overlap EXCLUDE USING gist (
        int8range(group_id, group_id, '[]') WITH =,
        daterange(starts_on, ends_on, '[]') WITH &&
    )
);

CREATE UNIQUE INDEX seasons_name_unique ON seasons (group_id, lower(name));

-- One or two parts per season (position 1 and 2), inside the season (checked
-- by the application in the writing transaction), in order, and not
-- overlapping. The overlap check is deferred so both parts can move in one
-- transaction.
CREATE TABLE season_parts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id BIGINT NOT NULL,
    season_id BIGINT NOT NULL,
    position SMALLINT NOT NULL,
    name VARCHAR(64) NOT NULL,
    starts_on DATE NOT NULL,
    ends_on DATE NOT NULL,
    -- Weeks alternate A/B; week 1 of the part (the Monday-based week holding
    -- starts_on) is A.
    alternating_weeks BOOLEAN NOT NULL DEFAULT false,
    created_at BIGINT NOT NULL,
    CONSTRAINT season_parts_group_id_unique UNIQUE (group_id, id),
    CONSTRAINT season_parts_position_unique UNIQUE (season_id, position),
    CONSTRAINT season_parts_position_valid CHECK (position IN (1, 2)),
    CONSTRAINT season_parts_name_nonempty CHECK (length(btrim(name)) > 0),
    CONSTRAINT season_parts_dates_ordered CHECK (starts_on < ends_on),
    CONSTRAINT season_parts_season_fk FOREIGN KEY (group_id, season_id)
        REFERENCES seasons (group_id, id) ON DELETE CASCADE,
    CONSTRAINT season_parts_no_overlap EXCLUDE USING gist (
        int8range(season_id, season_id, '[]') WITH =,
        daterange(starts_on, ends_on, '[]') WITH &&
    ) DEFERRABLE INITIALLY DEFERRED
);

-- Coaches of a team in a season. The coach must hold the coach role:
-- removing the role, or the member, removes their assignments. At most one
-- head coach per team and season.
CREATE TABLE season_team_coaches (
    group_id BIGINT NOT NULL,
    season_id BIGINT NOT NULL,
    team_id BIGINT NOT NULL,
    coach_user_id BIGINT NOT NULL,
    coach_role VARCHAR(16) NOT NULL DEFAULT 'coach',
    is_head BOOLEAN NOT NULL DEFAULT false,
    created_at BIGINT NOT NULL,
    PRIMARY KEY (season_id, team_id, coach_user_id),
    CONSTRAINT season_team_coaches_role_fixed CHECK (coach_role = 'coach'),
    CONSTRAINT season_team_coaches_season_fk FOREIGN KEY (group_id, season_id)
        REFERENCES seasons (group_id, id) ON DELETE CASCADE,
    CONSTRAINT season_team_coaches_team_fk FOREIGN KEY (group_id, team_id)
        REFERENCES teams (group_id, id) ON DELETE CASCADE,
    CONSTRAINT season_team_coaches_coach_fk FOREIGN KEY (group_id, coach_user_id, coach_role)
        REFERENCES group_member_roles (group_id, user_id, role) ON DELETE CASCADE
);

CREATE UNIQUE INDEX season_team_coaches_one_head ON season_team_coaches (season_id, team_id) WHERE is_head;
CREATE INDEX season_team_coaches_coach_idx ON season_team_coaches (group_id, coach_user_id);
CREATE INDEX season_team_coaches_team_idx ON season_team_coaches (group_id, team_id);
