-- Events (#8): trainings, matches, championships, and other events of one or
-- more teams, at a resource or a free-text location. Times are instants
-- computed from the wall-clock time entered in the group's time zone.
-- Sign-up and attendance (#9), statistics (#11), and generated events (#15)
-- reference an event as (group_id, event_id), so a reference never crosses
-- groups.
CREATE TABLE events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id BIGINT NOT NULL,
    kind VARCHAR(16) NOT NULL,
    title VARCHAR(128) NOT NULL,
    starts_at TIMESTAMPTZ NOT NULL,
    ends_at TIMESTAMPTZ NOT NULL,
    -- Exactly one of a resource of the group and a free-text location.
    resource_id BIGINT,
    location VARCHAR(255),
    signup_mode VARCHAR(16) NOT NULL DEFAULT 'open',
    -- Optional participant limit and sign-up deadline; #9 enforces them.
    max_participants SMALLINT,
    signup_deadline TIMESTAMPTZ,
    -- Cancelled events stay and are shown as cancelled.
    cancelled_at BIGINT,
    -- Set for events generated from the weekly plan (#15). The plan training
    -- foreign key arrives with plan_trainings (#14).
    plan_training_id BIGINT,
    -- Monday of the week the event was generated for (#15).
    generated_for_week DATE,
    -- Set when a generated event is changed by hand, so regenerating the
    -- week keeps it (#15).
    edited_at BIGINT,
    created_at BIGINT NOT NULL,
    -- Covers the event, its teams, and its extra coaches: they are edited
    -- together.
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT events_group_id_unique UNIQUE (group_id, id),
    CONSTRAINT events_kind_allowed CHECK (kind IN ('training', 'match', 'championship', 'other')),
    CONSTRAINT events_title_nonempty CHECK (length(btrim(title)) > 0),
    CONSTRAINT events_times_ordered CHECK (starts_at < ends_at),
    CONSTRAINT events_place_exclusive CHECK ((resource_id IS NULL) <> (location IS NULL)),
    CONSTRAINT events_location_nonempty CHECK (location IS NULL OR length(btrim(location)) > 0),
    CONSTRAINT events_signup_mode_allowed CHECK (signup_mode IN ('open', 'nominated')),
    CONSTRAINT events_max_participants_valid CHECK (max_participants IS NULL OR max_participants BETWEEN 1 AND 999),
    CONSTRAINT events_signup_deadline_valid CHECK (signup_deadline IS NULL OR signup_deadline < starts_at),
    CONSTRAINT events_generated_week_monday CHECK (generated_for_week IS NULL OR extract(isodow FROM generated_for_week) = 1),
    CONSTRAINT events_version_nonnegative CHECK (version >= 0),
    CONSTRAINT events_group_id_fk FOREIGN KEY (group_id) REFERENCES groups (id) ON DELETE CASCADE,
    CONSTRAINT events_resource_fk FOREIGN KEY (group_id, resource_id) REFERENCES resources (group_id, id)
);

CREATE INDEX events_group_starts_idx ON events (group_id, starts_at);
CREATE INDEX events_resource_idx ON events (group_id, resource_id, starts_at) WHERE resource_id IS NOT NULL;
CREATE INDEX events_plan_training_idx ON events (group_id, plan_training_id) WHERE plan_training_id IS NOT NULL;

-- The teams of an event (one or more).
CREATE TABLE event_teams (
    group_id BIGINT NOT NULL,
    event_id BIGINT NOT NULL,
    team_id BIGINT NOT NULL,
    PRIMARY KEY (event_id, team_id),
    CONSTRAINT event_teams_event_fk FOREIGN KEY (group_id, event_id)
        REFERENCES events (group_id, id) ON DELETE CASCADE,
    CONSTRAINT event_teams_team_fk FOREIGN KEY (group_id, team_id)
        REFERENCES teams (group_id, id) ON DELETE CASCADE
);

CREATE INDEX event_teams_team_idx ON event_teams (group_id, team_id);

-- Extra coaches of an event, on top of its teams' season coaches. The coach
-- must hold the coach role: removing the role, or the member, removes them.
CREATE TABLE event_coaches (
    group_id BIGINT NOT NULL,
    event_id BIGINT NOT NULL,
    coach_user_id BIGINT NOT NULL,
    coach_role VARCHAR(16) NOT NULL DEFAULT 'coach',
    PRIMARY KEY (event_id, coach_user_id),
    CONSTRAINT event_coaches_role_fixed CHECK (coach_role = 'coach'),
    CONSTRAINT event_coaches_event_fk FOREIGN KEY (group_id, event_id)
        REFERENCES events (group_id, id) ON DELETE CASCADE,
    CONSTRAINT event_coaches_coach_fk FOREIGN KEY (group_id, coach_user_id, coach_role)
        REFERENCES group_member_roles (group_id, user_id, role) ON DELETE CASCADE
);

CREATE INDEX event_coaches_coach_idx ON event_coaches (group_id, coach_user_id);
