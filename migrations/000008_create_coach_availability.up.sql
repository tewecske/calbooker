-- Coach qualifications and weekly availability per season part (#7).
-- Both reference the member's coach role, so removing the role (or the
-- member) removes the coach's qualification and availability.

-- The age range (whole years) a coach can coach in the group. A team's age
-- in a season is the season's start year minus the team's birth years.
CREATE TABLE coach_qualifications (
    group_id BIGINT NOT NULL,
    coach_user_id BIGINT NOT NULL,
    coach_role VARCHAR(16) NOT NULL DEFAULT 'coach',
    min_age SMALLINT NOT NULL,
    max_age SMALLINT NOT NULL,
    updated_at BIGINT NOT NULL,
    PRIMARY KEY (group_id, coach_user_id),
    CONSTRAINT coach_qualifications_role_fixed CHECK (coach_role = 'coach'),
    CONSTRAINT coach_qualifications_ages_valid CHECK (min_age >= 0 AND max_age <= 99 AND min_age <= max_age),
    CONSTRAINT coach_qualifications_coach_fk FOREIGN KEY (group_id, coach_user_id, coach_role)
        REFERENCES group_member_roles (group_id, user_id, role) ON DELETE CASCADE
);

-- Weekly time windows in which a coach is available, per season part. Week
-- is 'all' or, for parts with alternating weeks, 'A' or 'B' (checked by the
-- application). Minutes are after local midnight; weekday 1 is Monday.
-- Overlapping or touching windows of one coach, part, week, and weekday are
-- merged by the application, which rewrites a coach's windows of a part in
-- one transaction.
CREATE TABLE coach_availability (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id BIGINT NOT NULL,
    season_part_id BIGINT NOT NULL,
    coach_user_id BIGINT NOT NULL,
    coach_role VARCHAR(16) NOT NULL DEFAULT 'coach',
    week VARCHAR(3) NOT NULL,
    weekday SMALLINT NOT NULL,
    start_minute SMALLINT NOT NULL,
    end_minute SMALLINT NOT NULL,
    created_at BIGINT NOT NULL,
    CONSTRAINT coach_availability_role_fixed CHECK (coach_role = 'coach'),
    CONSTRAINT coach_availability_week_valid CHECK (week IN ('A', 'B', 'all')),
    CONSTRAINT coach_availability_weekday_valid CHECK (weekday BETWEEN 1 AND 7),
    CONSTRAINT coach_availability_minutes_valid CHECK (start_minute >= 0 AND start_minute < end_minute AND end_minute <= 1440),
    CONSTRAINT coach_availability_part_fk FOREIGN KEY (group_id, season_part_id)
        REFERENCES season_parts (group_id, id) ON DELETE CASCADE,
    CONSTRAINT coach_availability_coach_fk FOREIGN KEY (group_id, coach_user_id, coach_role)
        REFERENCES group_member_roles (group_id, user_id, role) ON DELETE CASCADE
);

CREATE INDEX coach_availability_part_idx ON coach_availability (group_id, season_part_id, coach_user_id);
CREATE INDEX coach_availability_coach_idx ON coach_availability (group_id, coach_user_id);
