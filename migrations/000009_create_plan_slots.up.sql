-- Resource slots of a season part's weekly plan (#13): when a resource is
-- open for trainings, optionally for an age range and a number of teams.
-- Times are minutes after local midnight in the group's time zone; weekday
-- is ISO (1 = Monday); week is 'A' or 'B' in parts with alternating weeks,
-- 'all' for every week. Slots may overlap. Training plans (#14) reference a
-- slot as (group_id, plan_slot_id).
CREATE TABLE plan_slots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id BIGINT NOT NULL,
    season_part_id BIGINT NOT NULL,
    resource_id BIGINT NOT NULL,
    week VARCHAR(3) NOT NULL DEFAULT 'all',
    weekday SMALLINT NOT NULL,
    start_minute SMALLINT NOT NULL,
    end_minute SMALLINT NOT NULL,
    min_age SMALLINT,
    max_age SMALLINT,
    max_teams SMALLINT,
    created_at BIGINT NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT plan_slots_group_id_unique UNIQUE (group_id, id),
    CONSTRAINT plan_slots_week_allowed CHECK (week IN ('A', 'B', 'all')),
    CONSTRAINT plan_slots_weekday_valid CHECK (weekday BETWEEN 1 AND 7),
    CONSTRAINT plan_slots_minutes_valid CHECK (start_minute >= 0 AND start_minute < end_minute AND end_minute <= 1440),
    CONSTRAINT plan_slots_min_age_valid CHECK (min_age IS NULL OR min_age BETWEEN 1 AND 99),
    CONSTRAINT plan_slots_max_age_valid CHECK (max_age IS NULL OR max_age BETWEEN 1 AND 99),
    CONSTRAINT plan_slots_ages_ordered CHECK (min_age IS NULL OR max_age IS NULL OR min_age <= max_age),
    CONSTRAINT plan_slots_max_teams_valid CHECK (max_teams IS NULL OR max_teams BETWEEN 1 AND 99),
    CONSTRAINT plan_slots_version_nonnegative CHECK (version >= 0),
    -- Removing a season part (or its season) removes its plan.
    CONSTRAINT plan_slots_part_fk FOREIGN KEY (group_id, season_part_id)
        REFERENCES season_parts (group_id, id) ON DELETE CASCADE,
    -- Resources are archived, never deleted, except with their group; the
    -- cascade lets the group's deletion remove its slots whichever
    -- reference PostgreSQL follows first.
    CONSTRAINT plan_slots_resource_fk FOREIGN KEY (group_id, resource_id)
        REFERENCES resources (group_id, id) ON DELETE CASCADE
);

CREATE INDEX plan_slots_part_idx ON plan_slots (group_id, season_part_id, weekday, start_minute);
CREATE INDEX plan_slots_resource_idx ON plan_slots (group_id, resource_id);
