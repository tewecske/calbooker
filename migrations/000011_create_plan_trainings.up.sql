-- Trainings of a season part's weekly plan (#14): a team trains on a
-- resource, usually inside a resource slot (#13) but at its own start and end,
-- so two teams can share a field at 16:00-17:30 and 17:00-18:30. Times are
-- minutes after local midnight in the group's time zone; weekday is ISO
-- (1 = Monday); week is 'A' or 'B' in parts with alternating weeks, 'all'
-- for every week. Generated events (#15) reference a training as
-- (group_id, plan_training_id).
CREATE TABLE plan_trainings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id BIGINT NOT NULL,
    season_part_id BIGINT NOT NULL,
    team_id BIGINT NOT NULL,
    resource_id BIGINT NOT NULL,
    plan_slot_id BIGINT,
    week VARCHAR(3) NOT NULL DEFAULT 'all',
    weekday SMALLINT NOT NULL,
    start_minute SMALLINT NOT NULL,
    end_minute SMALLINT NOT NULL,
    created_at BIGINT NOT NULL,
    CONSTRAINT plan_trainings_group_id_unique UNIQUE (group_id, id),
    -- Checked at commit, so one board save can swap two trainings.
    CONSTRAINT plan_trainings_unique_training UNIQUE (season_part_id, team_id, resource_id, week, weekday, start_minute, end_minute)
        DEFERRABLE INITIALLY DEFERRED,
    CONSTRAINT plan_trainings_week_allowed CHECK (week IN ('A', 'B', 'all')),
    CONSTRAINT plan_trainings_weekday_valid CHECK (weekday BETWEEN 1 AND 7),
    CONSTRAINT plan_trainings_minutes_valid CHECK (start_minute >= 0 AND start_minute < end_minute AND end_minute <= 1440),
    -- Removing a season part (or its season) removes its plan.
    CONSTRAINT plan_trainings_part_fk FOREIGN KEY (group_id, season_part_id)
        REFERENCES season_parts (group_id, id) ON DELETE CASCADE,
    -- Teams are deleted with their group or by hand; resources only with
    -- their group (they are archived otherwise). Either way the training
    -- goes with them.
    CONSTRAINT plan_trainings_team_fk FOREIGN KEY (group_id, team_id)
        REFERENCES teams (group_id, id) ON DELETE CASCADE,
    CONSTRAINT plan_trainings_resource_fk FOREIGN KEY (group_id, resource_id)
        REFERENCES resources (group_id, id) ON DELETE CASCADE,
    -- A deleted slot leaves its trainings in place, without a slot. Only
    -- plan_slot_id is cleared: group_id is part of the same foreign key and
    -- must stay.
    CONSTRAINT plan_trainings_slot_fk FOREIGN KEY (group_id, plan_slot_id)
        REFERENCES plan_slots (group_id, id) ON DELETE SET NULL (plan_slot_id)
);

CREATE INDEX plan_trainings_part_idx ON plan_trainings (group_id, season_part_id, weekday, start_minute);
CREATE INDEX plan_trainings_team_idx ON plan_trainings (group_id, team_id);
CREATE INDEX plan_trainings_resource_idx ON plan_trainings (group_id, resource_id);
CREATE INDEX plan_trainings_slot_idx ON plan_trainings (group_id, plan_slot_id) WHERE plan_slot_id IS NOT NULL;

-- Events generated from a training (#15) keep the link to it; deleting the
-- training keeps the event and clears only the link.
ALTER TABLE events
    ADD CONSTRAINT events_plan_training_fk FOREIGN KEY (group_id, plan_training_id)
        REFERENCES plan_trainings (group_id, id) ON DELETE SET NULL (plan_training_id);
