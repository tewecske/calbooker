-- Map existing rows to their group's kind, then drop the code columns.
ALTER TABLE events ADD COLUMN kind_id BIGINT;
UPDATE events e SET kind_id = k.id FROM event_kinds k WHERE k.group_id = e.group_id AND k.system_code = e.kind;
ALTER TABLE events ALTER COLUMN kind_id SET NOT NULL;
ALTER TABLE events DROP CONSTRAINT events_kind_allowed;
ALTER TABLE events DROP COLUMN kind;
ALTER TABLE events ADD CONSTRAINT events_kind_fk FOREIGN KEY (group_id, kind_id) REFERENCES event_kinds (group_id, id);
CREATE INDEX events_kind_idx ON events (group_id, kind_id);

ALTER TABLE resources ADD COLUMN kind_id BIGINT;
UPDATE resources r SET kind_id = k.id FROM resource_kinds k WHERE k.group_id = r.group_id AND k.system_code = r.kind;
ALTER TABLE resources ALTER COLUMN kind_id SET NOT NULL;
ALTER TABLE resources DROP CONSTRAINT resources_kind_allowed;
ALTER TABLE resources DROP COLUMN kind;
ALTER TABLE resources ADD CONSTRAINT resources_kind_fk FOREIGN KEY (group_id, kind_id) REFERENCES resource_kinds (group_id, id);
CREATE INDEX resources_kind_idx ON resources (group_id, kind_id);
