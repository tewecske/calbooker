-- Event kinds and resource kinds managed per group (#43). They replace the
-- fixed lists of #4 and #8: every group has its own rows with a name in each
-- language, a position, and an archived state. Events and resources reference
-- (group_id, kind_id), so a kind can never cross groups. A kind in use cannot
-- be deleted (the foreign keys refuse it).
--
-- system_code marks the kinds the application knows by a stable code. It is
-- NULL for kinds an administrator added. Seeded rows keep the code of the
-- old fixed value ('training', 'match', ...); only event kind 'training'
-- carries behaviour (event generation, #15) and cannot be deleted or
-- archived. Keep the default rows in step with service.DefaultEventKinds and
-- service.DefaultResourceKinds.
CREATE TABLE event_kinds (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id BIGINT NOT NULL,
    system_code VARCHAR(16),
    name_en VARCHAR(48) NOT NULL,
    -- Empty means "show the English name".
    name_hu VARCHAR(48) NOT NULL DEFAULT '',
    position INTEGER NOT NULL,
    archived_at BIGINT,
    created_at BIGINT NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT event_kinds_group_id_unique UNIQUE (group_id, id),
    CONSTRAINT event_kinds_system_code_unique UNIQUE (group_id, system_code),
    CONSTRAINT event_kinds_name_en_nonempty CHECK (length(btrim(name_en)) > 0),
    CONSTRAINT event_kinds_position_nonnegative CHECK (position >= 0),
    CONSTRAINT event_kinds_version_nonnegative CHECK (version >= 0),
    CONSTRAINT event_kinds_group_id_fk FOREIGN KEY (group_id) REFERENCES groups (id) ON DELETE CASCADE
);

CREATE UNIQUE INDEX event_kinds_active_name_unique ON event_kinds (group_id, lower(name_en)) WHERE archived_at IS NULL;
CREATE INDEX event_kinds_group_idx ON event_kinds (group_id, position, id);

CREATE TABLE resource_kinds (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id BIGINT NOT NULL,
    system_code VARCHAR(16),
    name_en VARCHAR(48) NOT NULL,
    name_hu VARCHAR(48) NOT NULL DEFAULT '',
    position INTEGER NOT NULL,
    archived_at BIGINT,
    created_at BIGINT NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT resource_kinds_group_id_unique UNIQUE (group_id, id),
    CONSTRAINT resource_kinds_system_code_unique UNIQUE (group_id, system_code),
    CONSTRAINT resource_kinds_name_en_nonempty CHECK (length(btrim(name_en)) > 0),
    CONSTRAINT resource_kinds_position_nonnegative CHECK (position >= 0),
    CONSTRAINT resource_kinds_version_nonnegative CHECK (version >= 0),
    CONSTRAINT resource_kinds_group_id_fk FOREIGN KEY (group_id) REFERENCES groups (id) ON DELETE CASCADE
);

CREATE UNIQUE INDEX resource_kinds_active_name_unique ON resource_kinds (group_id, lower(name_en)) WHERE archived_at IS NULL;
CREATE INDEX resource_kinds_group_idx ON resource_kinds (group_id, position, id);

