#!/bin/sh
# Prepares local development against the goweb single sign-on stack: creates
# the calbooker database in goweb's PostgreSQL container and (re)registers the
# development client in goweb's Hydra container, then prints the settings
# `make dev-setup` writes to the git-ignored .env.local. Re-running is safe; it
# keeps the database and rotates the client secret.
#
# Needs, from the goweb checkout (GOWEB_DIR, default ../goweb):
#   make db-up        PostgreSQL (container goweb-postgres)
#   make sso-up       Hydra (container goweb-hydra)
#   make run-provider the provider
#
# Addresses come from goweb's .env (SSO_DEV_*), so calbooker follows the same
# loopback or tailnet layout as goweb's development client. Override with:
#   CALBOOKER_DEV_URL           where browsers reach calbooker; default: the
#                               goweb client host (SSO_DEV_CLIENT_URL) on port
#                               8082, else http://127.0.0.1:8082
#   CALBOOKER_DEV_BIND          listen address; default SSO_DEV_BIND, else 127.0.0.1
#   CALBOOKER_DEV_ISSUER_URL    default SSO_DEV_ISSUER_URL, else http://127.0.0.1:4444
#   CALBOOKER_DEV_PROVIDER_URL  default SSO_DEV_PROVIDER_URL, else http://localhost:8080
#
# Hydra only calls loopback and private addresses, so when calbooker listens
# elsewhere (a tailnet address) this starts a loopback relay container,
# calbooker-backchannel-relay on 127.0.0.1:4447, for back-channel logout.
set -eu

goweb_dir="${GOWEB_DIR:-../goweb}"
[ -f "$goweb_dir/.env" ] || { echo "no $goweb_dir/.env; set GOWEB_DIR to the goweb checkout and run its make db-up first" >&2; exit 2; }
# Read goweb's settings in a subshell so they never override the ones above.
goweb_env() { (set -a; . "$goweb_dir/.env" >/dev/null 2>&1; eval "printf '%s' \"\${$1:-}\""); }

pg_user="$(goweb_env POSTGRES_USER)"; pg_user="${pg_user:-goweb}"
pg_password="$(goweb_env POSTGRES_PASSWORD)"; pg_password="${pg_password:-goweb}"
pg_db="$(goweb_env POSTGRES_DB)"; pg_db="${pg_db:-goweb}"
pg_port="$(goweb_env POSTGRES_PORT)"; pg_port="${pg_port:-55432}"
dev_bind="$(goweb_env SSO_DEV_BIND)"
dev_issuer="$(goweb_env SSO_DEV_ISSUER_URL)"
dev_provider="$(goweb_env SSO_DEV_PROVIDER_URL)"
dev_client="$(goweb_env SSO_DEV_CLIENT_URL)"

default_url="http://127.0.0.1:8082"
if [ -n "$dev_client" ]; then
	default_url="${dev_client%:*}:8082"
fi
app_url="${CALBOOKER_DEV_URL:-$default_url}"
app_url="${app_url%/}"
case "$app_url" in
http://*:[0-9]* | https://*:[0-9]*) ;;
*) echo "CALBOOKER_DEV_URL must include a port, for example http://127.0.0.1:8082" >&2; exit 2 ;;
esac
port="${app_url##*:}"
bind="${CALBOOKER_DEV_BIND:-${dev_bind:-127.0.0.1}}"
issuer_url="${CALBOOKER_DEV_ISSUER_URL:-${dev_issuer:-http://127.0.0.1:4444}}"
provider_url="${CALBOOKER_DEV_PROVIDER_URL:-${dev_provider:-http://localhost:8080}}"
client_id="${CALBOOKER_DEV_CLIENT_ID:-calbooker-dev}"
db_name="${CALBOOKER_DEV_DATABASE:-calbooker}"

echo "SELECT 'CREATE DATABASE $db_name' WHERE NOT EXISTS (SELECT FROM pg_database WHERE datname = '$db_name') \\gexec" |
	docker exec -i goweb-postgres psql -X -q -v ON_ERROR_STOP=1 -U "$pg_user" -d "$pg_db" >/dev/null
echo "database $db_name ready" >&2

backchannel="http://127.0.0.1:$port/oauth/sso/backchannel-logout"
if [ "$bind" != "127.0.0.1" ]; then
	docker rm -f calbooker-backchannel-relay >/dev/null 2>&1 || true
	docker run -d --name calbooker-backchannel-relay --network host alpine/socat:1.8.0.3 \
		"TCP-LISTEN:4447,bind=127.0.0.1,fork,reuseaddr" "TCP:$bind:$port" >/dev/null
	backchannel="http://127.0.0.1:4447/oauth/sso/backchannel-logout"
	echo "back-channel relay 127.0.0.1:4447 -> $bind:$port started" >&2
fi

secret="$(od -An -tx1 -N32 /dev/urandom | tr -d ' \n')"
hydra() { docker exec goweb-hydra hydra --endpoint http://127.0.0.1:4445 "$@"; }
hydra delete oauth2-client "$client_id" >/dev/null 2>&1 || true
hydra create oauth2-client \
	--id "$client_id" \
	--secret "$secret" \
	--name "Calbooker (development)" \
	--grant-type authorization_code \
	--response-type code \
	--scope openid,email,profile \
	--token-endpoint-auth-method client_secret_basic \
	--redirect-uri "$app_url/en/oauth/sso/callback" \
	--post-logout-callback "$app_url/en/sign-in" \
	--backchannel-logout-callback "$backchannel" \
	--backchannel-logout-session-required \
	--skip-consent \
	--skip-logout-consent \
	--format json >/dev/null
echo "registered $client_id for $app_url" >&2

cat <<ENV
# Generated by scripts/dev-setup.sh; overrides .env for make run. Re-run
# make dev-setup after Hydra's database is reset.
CALBOOKER_HTTP_ADDR=$bind:$port
CALBOOKER_PUBLIC_URL=$app_url
CALBOOKER_DATABASE_URL=postgres://$pg_user:$pg_password@localhost:$pg_port/$db_name?sslmode=disable
CALBOOKER_SSO_ISSUER_URL=$issuer_url
CALBOOKER_SSO_CLIENT_ID=$client_id
CALBOOKER_SSO_CLIENT_SECRET=$secret
CALBOOKER_SSO_ACCOUNT_URL=$provider_url/en/account/settings
ENV
